const { chromium } = require('playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({ executablePath: process.env.HALO_CHROMIUM_PATH || undefined, headless: true, args: ['--no-sandbox', '--enable-unsafe-swiftshader', '--use-gl=angle', '--use-angle=swiftshader'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto((process.env.HALO_TEST_URL || 'http://127.0.0.1:4173') + '/halo/?world=1');
    await page.getByRole('button', { name: '＋ New project', exact: true }).click();
    await page.locator('#project-form input[name=name]').fill('Saturn project');
    await page.locator('#project-form button.primary').click();
    await page.locator('nav [data-view="jarvis"]').click();
    const ring = page.getByRole('navigation', { name: 'Saturn portals' });
    assert.equal(await ring.locator('.saturn-portal').count(), 8);
    await ring.focus();
    await page.keyboard.press('ArrowRight');
    await page.keyboard.press('ArrowRight');
    assert.equal(await ring.locator('[aria-pressed="true"]').getAttribute('data-portal'), 'creative');
    await page.keyboard.press('Enter');
    await page.getByRole('region',{name:'Creative working session'}).waitFor();
    assert.equal(await page.evaluate(() => document.activeElement?.name), 'focus');
    await page.locator('#session-form input[name=focus]').fill('Sketch the chorus');
    await page.getByRole('button',{name:'Start session'}).click();
    const sessionBefore=await page.evaluate(() => { const s=JSON.parse(localStorage.getItem('halo.workspace.v1')); return {projectId:s.activeProjectId,session:s.projects[0].sessions[0]}; });
    assert.equal(sessionBefore.session.focus,'Sketch the chorus');
    await page.locator('nav [data-view="jarvis"]').click();
    await page.locator('.saturn-portal[data-portal="games"]').click();
    await page.getByText(/Games Hub is planned/).waitFor();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('halo.workspace.v1')).view), 'jarvis');
    await ring.locator('[data-portal="projects"]').click();
    await page.getByLabel('Working notes').waitFor();
    await page.getByRole('button', { name: 'Enter Halo World' }).click();
    await page.waitForFunction(() => document.body.dataset.mode === 'world');
    await page.keyboard.down('KeyD');
    await page.waitForFunction(() => document.querySelector('.world-root')?.dataset.nearby === 'more');
    await page.keyboard.up('KeyD');
    await page.keyboard.press('KeyE');
    await page.getByText(/This portal is planned; no application has opened/).waitFor();
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('halo.workspace.v1')).view), 'project');
    await page.getByRole('button', { name: 'Back to plaza' }).click();
    await page.getByText('Destinations without 3D movement').click();
    await page.locator('.world-destinations button').filter({hasText:'Creative Sessions'}).click();
    await page.getByRole('button',{name:'Open App'}).click();
    await page.getByRole('region',{name:'Creative working session'}).waitFor();
    assert.equal(await page.evaluate(() => document.activeElement?.name),'recap');
    const sessionAfter=await page.evaluate(() => { const s=JSON.parse(localStorage.getItem('halo.workspace.v1')); return {projectId:s.activeProjectId,session:s.projects[0].sessions[0]}; });
    assert.deepEqual(sessionAfter,sessionBefore);
    await page.getByRole('button', { name: 'Enter Halo World' }).click();
    await page.waitForFunction(() => document.body.dataset.mode === 'world');
    await page.getByRole('button', { name: 'Return to Desktop' }).click();
    assert.deepEqual(errors, []);
    await page.close();
    const mobile=await browser.newPage({viewport:{width:390,height:844}});
    await mobile.goto((process.env.HALO_TEST_URL || 'http://127.0.0.1:4173') + '/halo/');
    await mobile.getByRole('button',{name:'＋ New project',exact:true}).click();
    await mobile.locator('#project-form input[name=name]').fill('Mobile session');
    await mobile.locator('#project-form button.primary').click();
    await mobile.locator('nav [data-view="jarvis"]').click();
    await mobile.locator('.saturn-portal[data-portal="creative"]').click();
    await mobile.getByRole('region',{name:'Creative working session'}).waitFor();
    assert.equal(await mobile.evaluate(()=>document.activeElement?.name),'focus');
    assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true);
    await mobile.close();
    console.log('PASS Saturn portals: Creative Sessions shares a saved project across Desktop and World, opens on mobile Desktop, and planned Games/More remain honest');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
