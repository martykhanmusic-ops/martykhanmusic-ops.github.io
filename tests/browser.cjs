const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { existsSync } = require('node:fs');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.HALO_CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined), headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: {width:1440,height:1000} });
  let page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto((process.env.HALO_TEST_URL || 'http://127.0.0.1:4173') + '/halo/');
  await page.getByRole('button', { name: '＋ New project', exact:true }).click();
  await page.getByLabel('Project name', {exact:true}).fill('First record');
  await page.getByLabel('Description', {exact:true}).fill('A late night session');
  await page.getByRole('button', {name:'Create project ↗',exact:true}).click();
  await page.getByLabel('Working notes').fill('Verse 1\nA quiet orbit.');
  await page.getByRole('button',{name:'Save project',exact:true}).click();
  await page.getByLabel('New task',{exact:true}).fill('Record the hook');
  await page.getByRole('button',{name:'Add',exact:true}).click();
  await page.getByRole('checkbox',{name:'Record the hook',exact:true}).check();
  await page.close(); page = await context.newPage(); page.on('pageerror',e=>errors.push(e.message));
  await page.goto((process.env.HALO_TEST_URL || 'http://127.0.0.1:4173') + '/halo/');
  assert.equal(await page.getByLabel('Working notes').inputValue(),'Verse 1\nA quiet orbit.');
  assert.equal(await page.getByRole('checkbox',{name:'Record the hook',exact:true}).isChecked(),true);
  await page.getByRole('button',{name:'← All projects',exact:true}).click();
  await page.getByLabel('Search projects, notes & tasks').fill('hook');
  assert.equal(await page.getByRole('button',{name:'Open project ↗',exact:true}).count(),1);
  await page.getByRole('button',{name:'Resume project ↗',exact:true}).click();
  assert.equal(await page.getByLabel('Working notes').inputValue(),'Verse 1\nA quiet orbit.');
  await page.getByRole('button',{name:'← All projects',exact:true}).click();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'/tmp/halo-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Open Jarvis portal',exact:true}).click();
  assert.equal(await page.getByRole('heading',{name:'Your command center.',exact:true}).count(),1);
  await page.getByRole('button',{name:'◉ Overview',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'/tmp/halo-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), true);
  await page.getByRole('button',{name:'Resume project ↗',exact:true}).click();
  assert.equal(await page.getByLabel('Working notes').inputValue(),'Verse 1\nA quiet orbit.');
  await page.getByRole('button',{name:'✧ Open Jarvis',exact:true}).click();
  await page.locator('#plan-input').fill('Mix the chorus');
  await page.getByRole('button',{name:'Generate plan ↗',exact:true}).click();
  assert.match(await page.locator('.job-card').first().textContent(),/pending/);
  await page.reload();
  await page.getByRole('button',{name:'Run job',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.job-card .badge')?.textContent==='completed');
  assert.match(await page.locator('.task-result').first().textContent(),/Verified task created/);
  await page.locator('#plan-action').selectOption('delete_completed');
  await page.getByRole('button',{name:'Generate plan ↗',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Run job',exact:true}).count(),0);
  await page.getByRole('button',{name:'Approve deletion plan',exact:true}).click();
  assert.match(await page.locator('#status').textContent(),/Enable the deletion tool/);
  await page.locator('[data-permission="delete_completed"]').check();
  await page.getByRole('button',{name:'Approve deletion plan',exact:true}).click();
  await page.getByRole('button',{name:'Run job',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.job-card .badge')?.textContent==='completed');
  assert.match(await page.locator('.task-result').first().textContent(),/Verified deletion of 1/);
  await page.reload();
  assert.equal(await page.locator('.job-card').count(),2);
  await page.getByRole('button',{name:'completed',exact:true}).click();
  assert.equal(await page.locator('.job-card').count(),2);
  await page.getByRole('button',{name:'failed',exact:true}).click();
  assert.equal(await page.locator('.job-card').count(),0);
  await page.getByRole('button',{name:'all',exact:true}).click();
  await page.screenshot({path:'/tmp/jarvis-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth), true);
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'/tmp/jarvis-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'◉ Overview',exact:true}).click();
  await page.getByRole('button',{name:'Resume project ↗',exact:true}).click();
  assert.equal(await page.getByRole('checkbox',{name:'Record the hook',exact:true}).count(),0);
  assert.equal(await page.getByRole('checkbox',{name:'Mix the chorus',exact:true}).count(),1);
  // Prove persisted data is escaped rather than interpreted as markup.
  await page.locator('#edit-project').getByLabel('Project name',{exact:true}).fill('<img src=x onerror=alert(1)>');
  await page.getByRole('button',{name:'Save project',exact:true}).click();
  assert.equal(await page.locator('main img').count(),0);
  await page.getByRole('button',{name:'← All projects',exact:true}).click();
  await page.getByRole('button',{name:'＋ New project',exact:true}).focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('#project-dialog').evaluate(el=>el.open),true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#project-dialog').evaluate(el=>el.open),false);
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await page.evaluate(()=>matchMedia('(prefers-reduced-motion: reduce)').matches),true);
  // Quota errors must be visible, without pretending to have saved.
  await page.getByRole('button',{name:'Resume project ↗',exact:true}).click();
  await page.getByLabel('Working notes').fill('Not persisted');
  await page.evaluate(()=>{Storage.prototype.setItem=()=>{throw new Error('Quota exceeded')};});
  await page.getByRole('button',{name:'Save project',exact:true}).click();
  assert.match(await page.locator('#status').textContent(),/Save failed/);
  assert.equal(await page.locator('#save-state').textContent(),'Unsaved changes');
  page.on('dialog',dialog=>dialog.accept());
  await page.reload();
  assert.equal(await page.getByLabel('Working notes').inputValue(),'Verse 1\nA quiet orbit.');
  assert.deepEqual(errors,[]);
  console.log('PASS: Halo create/save/reopen/resume/search/tasks, Jarvis plan/run/reload/history, granular permissions, deletion approval and verified effects, keyboard dialog, reduced motion, escaped content and visible save failure. Desktop/mobile: no overflow or JavaScript errors.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
