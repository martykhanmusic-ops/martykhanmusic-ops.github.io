const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const {existsSync}=require('node:fs');
const {readFile}=require('node:fs/promises');
const origin=process.env.HALO_TEST_URL||'http://127.0.0.1:4173';
(async()=>{
  const browser=await chromium.launch({executablePath:process.env.HALO_CHROMIUM_PATH||(existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined),headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
  try{
    const context=await browser.newContext({viewport:{width:1440,height:1000}}),page=await context.newPage(),errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
    const click=name=>page.getByRole('button',{name,exact:true}).click();
    const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('halo.workspace.v1')));
    await page.goto(`${origin}/halo/?world=1`);
    await click('＋ New project');await page.locator('#project-form input[name="name"]').fill('Workstation project');await click('Create project ↗');
    await page.getByLabel('Working notes').fill('Saved from Desktop');await click('Save project');
    const id=(await state()).activeProjectId;
    await page.getByLabel('Working notes').fill('Unsaved before entering World');
    await page.getByLabel('Working notes').evaluate(el=>{window.editorNode=el;window.shellNode=document.querySelector('.shell');});
    await click('Enter Halo World');await page.waitForFunction(()=>document.body.dataset.mode==='world');
    await click('Projects destination');await click('Use in World');
    assert.equal(await page.locator('.world-workstation .shell').count(),1);
    assert.equal(await page.getByLabel('Working notes').evaluate(el=>el===window.editorNode),true);
    assert.equal(await page.getByLabel('Working notes').inputValue(),'Unsaved before entering World');
    await page.getByLabel('Working notes').fill('Saved at the World workstation');await click('Save project');
    await page.getByLabel('New task',{exact:true}).fill('Approved cleanup target');await click('Add');
    await page.getByRole('checkbox',{name:'Approved cleanup target',exact:true}).check();
    await click('✧ Open Jarvis');
    await page.locator('#plan-action').selectOption('delete_completed');await click('Generate plan ↗');
    assert.equal(await page.getByRole('button',{name:'Run job',exact:true}).count(),0);
    await click('Approve deletion plan');assert.match(await page.locator('#status').textContent(),/Enable the deletion tool/);
    assert.equal((await state()).projects[0].tasks.length,1);
    await page.locator('[data-permission="delete_completed"]').check();await click('Approve deletion plan');await click('Run job');
    await page.waitForFunction(()=>JSON.parse(localStorage.getItem('halo.workspace.v1')).jobs[0].status==='completed');
    assert.equal((await state()).projects[0].tasks.length,0);
    assert.deepEqual((await state()).jobs[0].logs.map(log=>log.event),['planned','approved','started','verified']);
    const downloadPromise=page.waitForEvent('download');await click('Export backup');
    const download=await downloadPromise;await download.saveAs('/tmp/halo-world-workstation-backup.json');
    const backup=JSON.parse(await readFile('/tmp/halo-world-workstation-backup.json','utf8'));
    assert.equal(backup.projects[0].notes,'Saved at the World workstation');
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('#backup-file').setInputFiles('/tmp/halo-world-workstation-backup.json');
    await page.waitForFunction(()=>document.querySelector('#status')?.textContent==='Workspace restored.');
    assert.equal((await state()).permissions.delete_completed,false);
    assert.equal((await state()).jobs[0].status,'completed');
    await page.screenshot({path:'/tmp/halo-world-workstation.png'});
    await click('Close workstation');await click('Return to Desktop');
    assert.equal(await page.locator('.shell').evaluate(el=>el===window.shellNode),true);
    assert.equal(await page.locator('.world-workstation').count(),0);assert.equal(await page.locator('canvas').count(),0);
    assert.equal((await state()).activeProjectId,id);assert.equal((await state()).projects.length,1);
    assert.equal((await state()).projects[0].notes,'Saved at the World workstation');
    await page.locator('nav [data-view="dashboard"]').first().click();await click('Resume project ↗');
    await page.getByLabel('Working notes').fill('Draft during context loss');
    await click('Enter Halo World');await page.waitForFunction(()=>document.body.dataset.mode==='world');
    await click('Projects destination');await click('Use in World');
    await page.locator('canvas').evaluate(canvas=>{const gl=canvas.getContext('webgl2')||canvas.getContext('webgl');gl.getExtension('WEBGL_lose_context').loseContext();});
    await page.waitForFunction(()=>document.body.dataset.mode==='desktop');
    assert.equal(await page.getByLabel('Working notes').inputValue(),'Draft during context loss');
    assert.equal(await page.locator('.shell').evaluate(el=>el===window.shellNode),true);
    page.once('dialog',dialog=>dialog.accept());await page.reload();
    assert.equal(await page.getByLabel('Working notes').inputValue(),'Saved at the World workstation');
    assert.deepEqual(errors,[]);await context.close();
    console.log('PASS World M4: same live mount/draft, real notes/tasks, unchanged Jarvis permission/deletion approval/audit, close/return, workstation context-loss rescue, saved-data reload; no page errors.');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
